// Матрица условной видимости ТЭГов карточки 112.
//
// Правила (ТЗ КАРТОЧКА 112.docx + решения пользователя):
// - Ветка 101, признак не выбран: только Где, Признак, Доступ. Связанные
//   ряды появляются лишь после нажатия «Открытое пламя».
// - Ветка 101, «Открытое пламя», но «Где» не выбрано: тоже только
//   Где, Признак, Доступ — детализация (и всё ниже) появляется,
//   когда выбрано конкретное «Где» (список опций — под него).
// - Ветка 101, «Открытое пламя» + «Где»: видны все ряды.
// - Ветка 101, признак «Запах гари»: остаются Где, Признак, Доступ, Место
//   и Описание; детализация, угроза, медпомощь, эвакуация, нарушение
//   и газификация скрыты (значения очищаются, в БД не уходят).
// - Общая ветка, информационные типы (без выезда): только «Описание».
// - Общая ветка, операционные типы: полный набор ТЭГов.
//
// «Описание» (tagDesc) видимо всегда и в списки не входит.

// Типы без выезда служб: автоподбор отключён, виден только Описание.
export const INFO_TYPES = [
  'Отмена вызова',
  'Ошибочно набран номер',
  'Тестовый вызов',
  'Тренировка',
  'Передача дежурства',
  'Нецелевой вызов',
  'Консультация',
  'Вызов на иностранном языке',
  'Справка 101',
  'Справка 102',
  'Справка 103',
  'Справка 104',
  'Справка ГИБДД',
  'Справка Городское хозяйство',
  'Справка МЧС',
  'Благодарность службам',
  'Жалоба на действие или бездействие служб',
  'Технический сбой (сбой в работе с оборудованием 112 Москва)',
];

export const FIRE101_ROWS = [
  'where',
  'sign',
  'access',
  'detail',
  'place',
  'threat',
  'violation',
  'medical',
  'evac',
  'gas',
];

export const GENERIC_ROWS = ['threat', 'violation', 'medical', 'evac', 'gas'];

// Ряды ветки 101, скрываемые при признаке «Запах гари».
export const SMELL_HIDDEN = ['detail', 'threat', 'medical', 'evac', 'violation', 'gas'];

// Ряды ветки 101, видимые до выбора признака.
export const BASE_ROWS = ['where', 'sign', 'access'];

export const SMELL_SIGN = 'Запах гари';
export const FLAME_SIGN = 'Открытое пламя / Дым';

/**
 * Какие ряды ТЭГов показывать.
 * @param {{kind: string, title: string, tags: object}} params
 * @returns {string[]} ключи видимых рядов (без tagDesc — он виден всегда)
 */
export function visibleTagRows({ kind, title, tags }) {
  if (kind === 'fire101') {
    const sign = tags?.sign || '';
    if (sign === SMELL_SIGN) {
      return FIRE101_ROWS.filter((r) => !SMELL_HIDDEN.includes(r));
    }
    if (sign === FLAME_SIGN) {
      // Детализация имеет смысл только под конкретное «Где»
      // (улице — уличный список, транспорту — транспортный и т.д.).
      if (!tags?.where) return [...BASE_ROWS];
      return [...FIRE101_ROWS];
    }
    return [...BASE_ROWS];
  }
  if (INFO_TYPES.includes(title)) return [];
  return [...GENERIC_ROWS];
}

/**
 * Убрать значения скрытых рядов (скрыл ряд — значение не уйдёт в БД
 * и не подтянет лишние службы).
 */
export function pruneHiddenTags(tags, visible) {
  const allowed = new Set(visible);
  const next = { ...tags };
  for (const key of Object.keys(next)) {
    if (key !== 'tagDesc' && !allowed.has(key)) next[key] = '';
  }
  return next;
}
